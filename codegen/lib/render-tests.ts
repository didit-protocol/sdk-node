// One generated test per server operation (docs/DESIGN.md section 11): a mocked
// HTTP layer checks the method, the path (ids filled, application scope
// expanded), the query, the body encoding and the response parsing.

import { kebab } from "./naming.ts";
import type { Field, Method } from "./operations.ts";
import { isObject, type Json, type JsonObject, type Spec } from "./spec.ts";

const HEADER = "// Code generated by codegen from openapi/*.json. DO NOT EDIT.";

/** A file part in a synthesized multipart request. */
const FILE = Symbol("file");
// Json is `unknown`, so a synthesized value is just a Json that may hold FILE.
type Value = Json;

interface ResourceNodeLike {
  path: string;
  children: Map<string, ResourceNodeLike>;
  methods: Method[];
}

const FILE_LITERAL = `{ data: new Uint8Array([1, 2, 3]), filename: "document.jpg", contentType: "image/jpeg" }`;

// Spec examples that look like credentials (JWTs, live keys) are replaced, so the
// generated tests never carry token-shaped strings that secret scanners flag.
const TOKEN_LIKE = /^(eyJ|sk_live_|pk_live_|whsec_(?!test_))/;

function example<T extends Json>(value: T): T | string {
  return typeof value === "string" && TOKEN_LIKE.test(value) ? "sample-token" : value;
}

function typeMatches(schema: JsonObject, value: Json): boolean {
  switch (schema.type) {
    case "string":
      return typeof value === "string" && schema.format !== "binary";
    case "integer":
      return typeof value === "number" && Number.isInteger(value);
    case "number":
      return typeof value === "number";
    case "boolean":
      return typeof value === "boolean";
    default:
      return false;
  }
}

/** A value of `schema` that the generated parameter types accept. */
function synth(spec: Spec, raw: Json, depth = 0): Value {
  const schema = spec.resolveObject(raw);
  if (depth > 6) return null;
  const allOf = Array.isArray(schema.allOf) ? (schema.allOf as Json[]) : [];
  if (allOf.length === 1 && !isObject(schema.properties)) return synth(spec, allOf[0], depth + 1);
  for (const key of ["oneOf", "anyOf"]) {
    const members = schema[key];
    if (Array.isArray(members) && members.length) return synth(spec, members[0], depth + 1);
  }
  if (Array.isArray(schema.enum)) {
    const first = (schema.enum as Json[]).find((v) => v !== null);
    if (first !== undefined) return first;
  }
  if ("example" in schema && typeMatches(schema, schema.example)) return example(schema.example);
  switch (schema.type) {
    case "string":
      switch (schema.format) {
        case "date-time":
          return "2026-01-02T03:04:05Z";
        case "date":
          return "2026-01-02";
        case "uuid":
          return "00000000-0000-4000-8000-000000000001";
        case "email":
          return "user@example.com";
        case "uri":
          return "https://example.com/";
        case "binary":
          return FILE;
        default:
          return "value";
      }
    case "integer":
      return 1;
    case "number":
      return 1.5;
    case "boolean":
      return true;
    case "array":
      return [synth(spec, schema.items, depth + 1)] as Json;
    default:
      break;
  }
  const props: Record<string, Json> = {};
  const required = new Set<string>();
  const collect = (node: JsonObject): void => {
    for (const part of Array.isArray(node.allOf) ? (node.allOf as Json[]) : [])
      collect(spec.resolveObject(part));
    if (isObject(node.properties)) Object.assign(props, node.properties);
    if (Array.isArray(node.required)) for (const r of node.required) required.add(String(r));
  };
  collect(schema);
  if (Object.keys(props).length) {
    const out: Record<string, Value> = {};
    for (const [name, prop] of Object.entries(props)) {
      if (!required.has(name)) continue;
      if (spec.resolveObject(prop).readOnly === true) continue;
      out[name] = synth(spec, prop, depth + 1);
    }
    return out;
  }
  if (schema.type === "object" || "additionalProperties" in schema) return {};
  return "value";
}

function literal(value: Value): string {
  if (value === FILE) return FILE_LITERAL;
  if (Array.isArray(value)) return `[${value.map((v) => literal(v as Value)).join(", ")}]`;
  if (isObject(value)) {
    const entries = Object.entries(value).map(([k, v]) => `${JSON.stringify(k)}: ${literal(v)}`);
    return `{ ${entries.join(", ")} }`;
  }
  return JSON.stringify(value);
}

function hasFile(value: Value): boolean {
  if (value === FILE) return true;
  if (Array.isArray(value)) return value.some((v) => hasFile(v as Value));
  return false;
}

/** What a multipart text field carries for `value`. */
function formText(value: Json): string {
  if (typeof value === "string") return value;
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  return JSON.stringify(value);
}

/** `.name` when `name` is an identifier, else `["name"]`. */
function accessor(name: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? `.${name}` : `[${JSON.stringify(name)}]`;
}

function pathExample(method: Method, index: number): string {
  const arg = method.pathArgs[index]!;
  if (typeof arg.example === "string" && /^[A-Za-z0-9._~-]+$/.test(arg.example))
    return example(arg.example);
  return `${arg.wire.replace(/_/g, "-")}-${index + 1}`;
}

interface Case {
  title: string;
  code: string;
}

function renderCase(method: Method): Case {
  const { op } = method;
  const spec = op.spec;
  const pathValues = method.pathArgs.map((_, i) => pathExample(method, i));
  const params: Record<string, Value> = {};
  const query: Record<string, string> = {};
  const body: Record<string, Json> = {};
  const form: Record<string, string> = {};
  const files: string[] = [];
  let useMultipart = method.bodyMode === "multipart";
  let wholeBody: Value;

  if (method.wholeBody) {
    const schema = (() => {
      const rb = spec.resolveObject(op.op.requestBody);
      const content = isObject(rb.content) ? rb.content : {};
      const media = content["application/json"] ?? content["multipart/form-data"];
      return isObject(media) ? media.schema : {};
    })();
    wholeBody = synth(spec, schema);
  } else {
    const include = (field: Field): boolean =>
      field.required || (field.location === "query" && field.hasExample && field.example !== null);
    for (const field of method.fields) {
      if (!include(field)) continue;
      let value: Value;
      if (
        field.location === "query" &&
        field.hasExample &&
        typeMatches(spec.resolveObject(field.schema), field.example)
      ) {
        value = example(field.example);
      } else {
        value = synth(spec, field.schema);
      }
      if (value === null) continue;
      params[field.key] = value;
      if (field.location === "query") {
        query[field.wire] = formText(value);
      } else if (method.fileFields.includes(field.wire) || hasFile(value)) {
        files.push(field.wire);
        if (method.bodyMode === "auto") useMultipart = true;
      } else {
        body[field.wire] = value;
        form[field.wire] = formText(value);
      }
    }
  }

  const callArgs: string[] = pathValues.map((v) => JSON.stringify(v));
  if (method.params) {
    if (method.wholeBody) callArgs.push(literal(wholeBody ?? null));
    else if (Object.keys(params).length || method.paramsRequired) callArgs.push(literal(params));
  }
  const fullPath = (() => {
    let path = op.path;
    if (op.sdk.scope === "application") {
      path = path.replace("{organization_id}", "org-123").replace("{application_id}", "app-456");
    }
    method.pathArgs.forEach((arg, i) => {
      path = path.replace(`{${arg.wire}}`, encodeURIComponent(pathValues[i]!));
    });
    return path;
  })();

  const lines: string[] = [];
  const response = method.response;
  const reply: string[] = [`status: ${response.status}`];
  if (response.kind === "binary")
    reply.push(`body: BINARY, contentType: ${JSON.stringify(response.contentType)}`);
  else if (response.kind === "json") reply.push(`json: responseExample(${JSON.stringify(op.key)})`);
  else if (response.kind === "page")
    reply.push(`json: responseExample(${JSON.stringify(op.key)}, "page")`);
  lines.push(`    const { client, calls } = mockClient({ ${reply.join(", ")} });`);
  const call = `client.${op.sdk.resource
    .split(".")
    .map((s) => s.replace(/_([a-z0-9])/g, (_, c: string) => c.toUpperCase()))
    .join(".")}.${method.name}(${callArgs.join(", ")})`;
  if (response.kind === "page") lines.push(`    const page = await ${call};`);
  else if (response.kind === "none") lines.push(`    await ${call};`);
  else lines.push(`    const result = await ${call};`);
  lines.push(`    expect(calls).toHaveLength(1);`);
  lines.push(`    const request = calls[0]!;`);
  lines.push(`    expect(request.method).toBe(${JSON.stringify(op.httpMethod.toUpperCase())});`);
  lines.push(
    `    expect(request.origin).toBe(${op.api === "account" ? "ACCOUNT_ORIGIN" : "API_ORIGIN"});`,
  );
  lines.push(
    `    expect(request.path).toBe(${JSON.stringify(op.api === "account" ? `/auth/v2${fullPath}` : fullPath)});`,
  );
  lines.push(`    expect(request.query).toEqual(${JSON.stringify(query)});`);
  lines.push(`    expectAuth(request, ${JSON.stringify(op.sdk.auth)});`);
  lines.push(`    expect(request.headers.get("accept")).toBe(${JSON.stringify(response.accept)});`);
  if (method.wholeBody) {
    lines.push(`    expect(request.json).toEqual(${JSON.stringify(wholeBody ?? null)});`);
  } else if (useMultipart) {
    lines.push(`    expect(request.contentType).toMatch(/^multipart\\/form-data; boundary=/);`);
    lines.push(`    expect(request.form).toEqual(${JSON.stringify(form)});`);
    lines.push(
      `    expect(Object.keys(request.files).sort()).toEqual(${JSON.stringify(files.sort())});`,
    );
    for (const name of files) {
      lines.push(
        `    expect(request.files${accessor(name)}).toEqual([{ filename: "document.jpg", type: "image/jpeg", bytes: [1, 2, 3] }]);`,
      );
    }
  } else if (method.bodyMode !== "none") {
    lines.push(`    expect(request.contentType).toBe("application/json");`);
    lines.push(`    expect(request.json).toEqual(${JSON.stringify(body)});`);
  } else {
    lines.push(`    expect(request.bodyText).toBe("");`);
  }
  if (response.kind === "binary") {
    lines.push(`    expect(result).toBeInstanceOf(Blob);`);
    lines.push(`    expect(result.type).toBe(${JSON.stringify(response.contentType)});`);
    lines.push(`    expect([...new Uint8Array(await result.arrayBuffer())]).toEqual([...BINARY]);`);
  } else if (response.kind === "none") {
    // Nothing to parse.
  } else if (response.kind === "page") {
    const example = response.example;
    const hasNext = isObject(example) && typeof example.next === "string" && example.next !== "";
    lines.push(
      `    expectMatchesExample({ ...page }, responseExample(${JSON.stringify(op.key)}, "page"));`,
    );
    lines.push(`    expect(page.hasNextPage()).toBe(${hasNext});`);
  } else {
    lines.push(`    expectMatchesExample(result, responseExample(${JSON.stringify(op.key)}));`);
  }
  return {
    title: `${op.sdk.resource}.${op.sdk.method}: ${op.httpMethod.toUpperCase()} ${op.path}`,
    code: lines.join("\n"),
  };
}

export function renderTests(children: Map<string, ResourceNodeLike>): Map<string, string> {
  const out = new Map<string, string>();
  for (const [segment, node] of [...children.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    const all: Method[] = [];
    const walk = (n: ResourceNodeLike): void => {
      all.push(...n.methods);
      for (const c of n.children.values()) walk(c);
    };
    walk(node);
    all.sort((a, b) => `${a.resource}.${a.name}`.localeCompare(`${b.resource}.${b.name}`));
    const cases = all.map(renderCase);
    const usesBinary = all.some((m) => m.response.kind === "binary");
    const imports = ["expectAuth", "expectMatchesExample", "mockClient", "responseExample"];
    if (all.some((m) => m.op.api === "account")) imports.push("ACCOUNT_ORIGIN");
    if (all.some((m) => m.op.api !== "account")) imports.push("API_ORIGIN");
    if (usesBinary) imports.unshift("BINARY");
    const lines = [
      HEADER,
      "",
      `import { describe, expect, it } from "vitest";`,
      "",
      `import { ${imports.sort().join(", ")} } from "../helpers/mock-api.js";`,
      "",
      `describe(${JSON.stringify(node.path)}, () => {`,
      cases
        .map((c) => `  it(${JSON.stringify(c.title)}, async () => {\n${c.code}\n  });`)
        .join("\n\n"),
      "});",
      "",
    ];
    out.set(`tests/generated/${kebab(segment)}.test.ts`, lines.join("\n"));
  }
  return out;
}
