// Render the generated layer: src/types, src/resources and tests/generated.

import { kebab, propKey, resourceClass } from "./naming.ts";
import { buildMethod, responseComponents, type Method } from "./operations.ts";
import type { Model } from "./spec.ts";
import { declDeps, docLines, renderDecl, TypeBuilder, type Decl, type DatePlan } from "./types.ts";
import { renderTests } from "./render-tests.ts";

export const HEADER = "// Code generated by codegen from openapi/*.json. DO NOT EDIT.";

/** Names exported by the hand-written part of the package; generated types must not take them. */
export const RESERVED_NAMES = new Set([
  "Didit", "ClientOptions", "RequestOptions", "APIPromise", "APIResponse", "Page", "PagePromise",
  "PageResponse", "Uploadable", "FileUpload", "DiditError", "ConfigurationError", "APIConnectionError",
  "APITimeoutError", "APIResponseValidationError", "APIStatusError", "BadRequestError",
  "AuthenticationError", "PermissionDeniedError", "NotFoundError", "ConflictError",
  "UnprocessableEntityError", "RateLimitError", "InternalServerError", "WebhookVerificationError",
  "TokenVerificationError", "Authentication", "WebhookEvent", "UnknownEvent", "Logger", "LogLevel",
]);

export interface Rendered {
  files: Map<string, string>;
  methods: Method[];
  builder: TypeBuilder;
}

interface ResourceNode {
  path: string;
  className: string;
  children: Map<string, ResourceNode>;
  methods: Method[];
}

function tree(methods: Method[]): ResourceNode {
  const root: ResourceNode = { path: "", className: "DiditResources", children: new Map(), methods: [] };
  for (const method of methods) {
    let node = root;
    const segments = method.resource.split(".");
    segments.forEach((segment, i) => {
      let child = node.children.get(segment);
      if (!child) {
        const path = segments.slice(0, i + 1).join(".");
        child = { path, className: resourceClass(path), children: new Map(), methods: [] };
        node.children.set(segment, child);
      }
      node = child;
    });
    node.methods.push(method);
  }
  return root;
}

function camelSegment(segment: string): string {
  return segment.replace(/_([a-z0-9])/g, (_, c: string) => c.toUpperCase());
}

/** Imports for `deps`; `types` is the path from the importing file to src/types/. */
function importLines(deps: Set<string>, decls: Map<string, Decl>, from: string, types: string): string[] {
  const byModule = new Map<string, string[]>();
  let uploadable = false;
  for (const dep of deps) {
    if (dep === "@Uploadable") {
      uploadable = true;
      continue;
    }
    const decl = decls.get(dep);
    if (!decl) throw new Error(`codegen: unknown type ${dep}`);
    if (decl.module === from) continue;
    const list = byModule.get(decl.module) ?? [];
    list.push(dep);
    byModule.set(decl.module, list);
  }
  const lines: string[] = [];
  if (uploadable) lines.push(`import type { Uploadable } from "../core/uploads.js";`);
  for (const module of [...byModule.keys()].sort()) {
    const names = byModule.get(module)!.sort();
    lines.push(`import type { ${names.join(", ")} } from "${types}${kebab(module)}.js";`);
  }
  return lines;
}

function literalPlan(plan: DatePlan): string {
  return JSON.stringify(plan);
}

function descriptorFor(method: Method): string {
  const { op } = method;
  const parts: string[] = [`method: "${op.httpMethod.toUpperCase()}"`, `path: ${JSON.stringify(op.path)}`];
  if (op.api === "account") parts.push(`api: "account"`);
  if (op.sdk.auth === "account_token" || op.sdk.auth === "none") parts.push(`auth: "${op.sdk.auth}"`);
  if (op.sdk.scope === "application") parts.push(`scope: "application"`);
  const query = method.fields
    .filter((f) => f.location === "query")
    .map((f) => (f.key === f.wire ? f.wire : [f.key, f.wire]));
  if (query.length) parts.push(`query: ${JSON.stringify(query)}`);
  if (method.wholeBody) parts.push(`body: "whole"`);
  else if (method.bodyMode !== "none") parts.push(`body: "${method.bodyMode}"`);
  if (method.fileFields.length) parts.push(`files: ${JSON.stringify(method.fileFields)}`);
  if (method.response.kind === "binary") parts.push(`response: "binary"`, `accept: ${JSON.stringify(method.response.accept)}`);
  if (method.response.kind === "none") parts.push(`response: "none"`);
  if (method.response.plan !== null) parts.push(`dates: ${literalPlan(method.response.plan)}`);
  return `const ${method.constName}: OperationSpec = { ${parts.join(", ")} };`;
}

function methodDoc(method: Method): string[] {
  const lines: string[] = [];
  const { op } = method;
  const text: string[] = [];
  if (method.summary) text.push(method.summary);
  if (method.description && method.description !== method.summary) {
    if (text.length) text.push("");
    text.push(method.description);
  }
  if (text.length) text.push("");
  text.push(`\`${op.httpMethod.toUpperCase()} ${op.path}\``);
  if (method.idempotencyKey) {
    text.push("", "Accepts `options.idempotencyKey` (header `Idempotency-Key`).");
  }
  const tags: string[] = [];
  for (const arg of method.pathArgs) tags.push(`@param ${arg.name} ${arg.description ?? arg.wire}`.replace(/\n/g, " "));
  if (op.deprecated) tags.push(`@deprecated ${op.deprecationNote ?? "Deprecated in the API."}`);
  lines.push(...docLines(text.join("\n"), "  ", tags));
  return lines;
}

function methodSignature(method: Method): { args: string; call: string; returns: string } {
  const args: string[] = method.pathArgs.map((a) => `${a.name}: string`);
  const pathValues = `[${method.pathArgs.map((a) => a.name).join(", ")}]`;
  let paramsArg = "undefined";
  if (method.params) {
    if (method.paramsRequired) args.push(`params: ${method.params.expr}`);
    else if (method.wholeBody) args.push(`params?: ${method.params.expr}`);
    else args.push(`params: ${method.params.expr} = {}`);
    paramsArg = "params";
  }
  args.push("options?: RequestOptions");
  const response = method.response;
  if (response.kind === "page") {
    return {
      args: args.join(", "),
      call: `return this._client.requestPage(${method.constName}, ${pathValues}, ${paramsArg}, options);`,
      returns: `PagePromise<${response.type.expr}, ${response.item!.expr}>`,
    };
  }
  return {
    args: args.join(", "),
    call: `return this._client.request(${method.constName}, ${pathValues}, ${paramsArg}, options);`,
    returns: `APIPromise<${response.type.expr}>`,
  };
}

function renderResourceModule(top: ResourceNode, decls: Map<string, Decl>): string {
  const nodes: ResourceNode[] = [];
  const walk = (node: ResourceNode): void => {
    for (const child of [...node.children.values()]) walk(child);
    nodes.push(node);
  };
  walk(top);
  const deps = new Set<string>();
  const descriptors: string[] = [];
  let hasPage = false;
  let hasPromise = false;
  for (const node of nodes) {
    for (const method of node.methods) {
      for (const d of method.params?.deps ?? []) deps.add(d);
      for (const d of method.response.type.deps) deps.add(d);
      for (const d of method.response.item?.deps ?? []) deps.add(d);
      descriptors.push(descriptorFor(method));
      if (method.response.kind === "page") hasPage = true;
      else hasPromise = true;
    }
  }
  const out: string[] = [HEADER, ""];
  const coreImports: string[] = [];
  if (hasPromise) coreImports.push(`import type { APIPromise } from "../core/api-promise.js";`);
  coreImports.push(`import type { OperationSpec } from "../core/operation.js";`);
  if (hasPage) coreImports.push(`import type { PagePromise } from "../core/pagination.js";`);
  coreImports.push(`import type { RequestOptions } from "../core/request-options.js";`);
  const base = top.path === "webhooks" ? "WebhookHelpers" : "APIResource";
  const needsResource = nodes.some((node) => node !== top || base === "APIResource");
  if (needsResource) coreImports.push(`import { APIResource } from "../core/resource.js";`);
  out.push(...coreImports);
  out.push(...importLines(deps, decls, "", "../types/"));
  if (base === "WebhookHelpers") out.push(`import { WebhookHelpers } from "../webhooks/resource.js";`);
  out.push("", ...descriptors, "");
  for (const node of nodes) {
    const nodeBase = node === top ? base : "APIResource";
    out.push(`/** \`${node.path}\` */`);
    out.push(`export class ${node.className} extends ${nodeBase} {`);
    for (const [segment, child] of node.children) {
      out.push(`  readonly ${camelSegment(segment)}: ${child.className} = new ${child.className}(this._client);`);
    }
    if (node.children.size && node.methods.length) out.push("");
    node.methods
      .sort((a, b) => a.name.localeCompare(b.name))
      .forEach((method, index) => {
        if (index) out.push("");
        const sig = methodSignature(method);
        out.push(...methodDoc(method));
        out.push(`  ${method.name}(${sig.args}): ${sig.returns} {`);
        out.push(`    ${sig.call}`);
        out.push("  }");
      });
    out.push("}", "");
  }
  return out.join("\n");
}

function renderRoot(root: ResourceNode, plans: Map<string, DatePlan>): string {
  const out: string[] = [HEADER, ""];
  out.push(`import { APIClient } from "../core/api-client.js";`);
  out.push(`import type { DatePlan } from "../core/dates.js";`);
  const children = [...root.children.entries()].sort(([a], [b]) => a.localeCompare(b));
  for (const [segment, child] of children) {
    out.push(`import { ${child.className} } from "./${kebab(segment)}.js";`);
  }
  out.push("");
  out.push("/** Date-time decoding plans of the named response types (see core/dates.ts). */");
  out.push("export const DATE_PLANS: Readonly<Record<string, DatePlan>> = {");
  for (const name of [...plans.keys()].sort()) out.push(`  ${propKey(name)}: ${literalPlan(plans.get(name)!)},`);
  out.push("};", "");
  out.push("/** Every resource of the API, one property per top-level resource. */");
  out.push("export abstract class DiditResources extends APIClient {");
  out.push("  protected override readonly datePlans: Readonly<Record<string, DatePlan>> = DATE_PLANS;");
  for (const [segment, child] of children) {
    out.push(`  readonly ${camelSegment(segment)}: ${child.className} = new ${child.className}(this);`);
  }
  out.push("}", "");
  // Re-export every resource class, so users can name them in their own types.
  for (const [segment, child] of children) {
    const names: string[] = [];
    const collect = (node: ResourceNode): void => {
      names.push(node.className);
      for (const c of node.children.values()) collect(c);
    };
    collect(child);
    out.push(`export { ${names.sort().join(", ")} } from "./${kebab(segment)}.js";`);
  }
  out.push("");
  return out.join("\n");
}

function renderTypes(module: string, decls: Decl[], all: Map<string, Decl>): string {
  const deps = new Set<string>();
  for (const decl of decls) for (const d of declDeps(decl)) deps.add(d);
  const out: string[] = [HEADER, ""];
  const imports = importLines(deps, all, module, "./");
  if (imports.length) out.push(...imports, "");
  out.push(decls.map(renderDecl).join("\n\n"), "");
  return out.join("\n");
}

/** Build every generated file from the model. */
export function render(model: Model): Rendered {
  const builder = new TypeBuilder([model.specs.verification, model.specs.account], RESERVED_NAMES);
  const server = model.operations.filter((op) => op.sdk.server);
  builder.setResponseUsage(responseComponents(server));
  const methods = server
    .slice()
    .sort((a, b) => `${a.sdk.resource}.${a.sdk.method}`.localeCompare(`${b.sdk.resource}.${b.sdk.method}`))
    .map((op) => buildMethod(op, builder));
  const files = new Map<string, string>();

  const root = tree(methods);
  for (const [segment, node] of root.children) {
    files.set(`src/resources/${kebab(segment)}.ts`, renderResourceModule(node, builder.decls));
  }
  files.set("src/resources/index.ts", renderRoot(root, builder.plans));

  const byModule = new Map<string, Decl[]>();
  for (const decl of builder.decls.values()) {
    const list = byModule.get(decl.module) ?? [];
    list.push(decl);
    byModule.set(decl.module, list);
  }
  const modules = [...byModule.keys()].sort();
  for (const module of modules) {
    const decls = byModule.get(module)!.sort((a, b) => a.name.localeCompare(b.name));
    files.set(`src/types/${kebab(module)}.ts`, renderTypes(module, decls, builder.decls));
  }
  files.set(
    "src/types/index.ts",
    [HEADER, "", ...modules.map((m) => `export type * from "./${kebab(m)}.js";`), ""].join("\n"),
  );

  for (const [path, content] of renderTests(root.children, methods)) files.set(path, content);
  return { files, methods, builder };
}
